#pragma once

// Screens from a JSON document at run time, for UI that is not known when the
// program is built: sent by a tool, an agent or a server.
//
//   constexpr std::string_view doc = R"({
//     "type": "column",
//     "props": {"size": ["320px", "240px"]},
//     "children": [
//       {"type": "label", "id": "title", "props": {"text": "Speed"}},
//       {"type": "arc", "id": "speedo", "props": {"range": [0, 240], "value": 120}}
//     ]})";
//
//   using ui = lv::runtime<"obj", "label", "arc">;      // the widgets a document may use
//   auto screen = ui::load(doc, lv::screen_active());   // std::expected
//   screen->apply(R"({"speedo": {"value": 60}})");      // change properties by id
//
// A document can only do what the generated property tables allow: a widget that
// is not in the list, a property that does not exist and a value of the wrong kind
// are rejected, and nothing of a rejected document stays on the screen.
// The tables are generated by reflection from the same props structs as the
// compile-time tree, so both accept the same names.
//
// Values: numbers; true/false; strings for text; "120px", "50%" or "content" for
// lengths; "90deg", and "22.5deg" where LVGL takes tenths of a degree; "300ms";
// "#rrggbb"; an enumerator by name, in full ("LV_ALIGN_CENTER") or by its last part
// ("center"); a list for a property that takes several values. Handlers, bindings
// and pointers cannot come from a document.
//
// Limits: text values are at most 127 characters and are not unescaped. The
// document must stay alive as long as the loaded screen is used with find/apply
// (the ids are views into it). At most 32 nodes of a document can have an id.
// A table has at most 64 rows and columns, a chart 1024 points (detail::count_limits).

